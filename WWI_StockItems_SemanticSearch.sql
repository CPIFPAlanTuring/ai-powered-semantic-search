-- 5. Create stored procedures using the 
--    vector index for semantic product search
--=====================================================
/*
    Procedure: dbo.find_relevant_product_names_vector_index

    - Simple output 
    
    - Returns only the names of the semantically related products.
*/
USE [WideWorldImporters];
GO

CREATE OR ALTER PROCEDURE dbo.find_relevant_product_names_vector_index
    @prompt NVARCHAR(MAX),                 -- User search text
    @top INT = 10,                         -- Maximum number of returned products
    @min_similarity DECIMAL(19,16) = 0.3   -- Minimum accepted similarity
AS
BEGIN
    SET NOCOUNT ON;

    -- Basic validation of the search text
    IF @prompt IS NULL OR LTRIM(RTRIM(@prompt)) = N''
    BEGIN
        RAISERROR(N'Debe indicar un texto de búsqueda en @prompt.', 16, 1);
        RETURN;
    END;

    -- Basic validation of the number of results
    IF @top IS NULL OR @top <= 0
    BEGIN
        SET @top = 10;
    END;

    DECLARE @queryEmbedding vector(768);

    /*
        -- Generates the embedding for the user's query
        -- SQL Server calls the external model OllamaNomicEmbed,
           which in turn uses Ollama with nomic-embed-text.
    */
    SET @queryEmbedding =
        CAST(
            AI_GENERATE_EMBEDDINGS(
                @prompt
                USE MODEL OllamaNomicEmbed
            )
            AS vector(768)
        );
    /*
        -- Use VECTOR_SEARCH to compare the query vector with stored 
           product embeddings and return the closest product names
    */
    SELECT
        ps.StockItemName AS ProductName
    FROM VECTOR_SEARCH
    (
        TABLE = dbo.ProductSemantic AS ps,
        COLUMN = Embedding,
        SIMILAR_TO = @queryEmbedding,
        METRIC = 'cosine',
        TOP_N = @top
    ) AS vs
    WHERE CAST(1 - vs.distance AS DECIMAL(19,16)) >= @min_similarity
    ORDER BY vs.distance ASC;
END;
GO

--======================================================
-- DEMO SP: dbo.find_relevant_product_names_vector_index
--======================================================

EXEC dbo.find_relevant_product_names_vector_index
    @prompt = N'usb gadget',
    @top = 10,
    @min_similarity = 0.3;
GO

/*
    Notice:
        -Some results, although they do not contain “USB”,
         still belong to the same semantic context of 
         technology-related items.

        - Semantic search may return some less relevant results.
          This can happen when the embedding model considers them
          close to part of the user query.
 */

/*
