/*
    Procedure: dbo.find_relevant_products_vector_index

    - Technical view.

    - Shows SemanticText, distance and similarity.
*/
USE [WideWorldImporters];
GO

CREATE OR ALTER PROCEDURE dbo.find_relevant_products_vector_index
    @prompt NVARCHAR(MAX),                 -- User search text
    @top INT = 10,                         -- Maximum number of returned products
    @min_similarity DECIMAL(19,16) = 0.3   -- Minimum accepted similarity
AS
BEGIN
    SET NOCOUNT ON;

    -- Basic validation of the search text
    IF @prompt IS NULL OR LTRIM(RTRIM(@prompt)) = N''
    BEGIN
        RAISERROR(N'Debe indicar un texto de búsqueda en @prompt.', 16, 1);
        RETURN;
    END;

    -- Basic validation of the number of results
    IF @top IS NULL OR @top <= 0
    BEGIN
        SET @top = 10;
    END;

    DECLARE @queryEmbedding vector(768);
        
    SET @queryEmbedding =
        CAST(
            AI_GENERATE_EMBEDDINGS(
                @prompt
                USE MODEL OllamaNomicEmbed
            )
            AS vector(768)
        );

    SELECT
        ps.ProductSemanticID,
        ps.StockItemID,
        ps.StockItemName,
        ps.SemanticText,
        vs.distance, 
            -- low distance: more similar product
        CAST(1 - vs.distance AS DECIMAL(19,16)) AS similarity
            -- high similarity: more similar product
    FROM VECTOR_SEARCH
    (
        TABLE = dbo.ProductSemantic AS ps,
        COLUMN = Embedding,
        SIMILAR_TO = @queryEmbedding,
        METRIC = 'cosine',
        TOP_N = @top
    ) AS vs
    WHERE CAST(1 - vs.distance AS DECIMAL(19,16)) >= @min_similarity
    ORDER BY vs.distance ASC;
END;
GO

