/*
    Procedure: dbo.find_relevant_stock_items_vector_index

    - Real-world case.

    - Combines semantic search with business data.

*/
USE [WideWorldImporters];
GO

CREATE OR ALTER PROCEDURE dbo.find_relevant_stock_items_vector_index
    @prompt NVARCHAR(MAX),
    @top INT = 10,
    @min_similarity DECIMAL(19,16) = 0.3
AS
BEGIN
    SET NOCOUNT ON;

    IF @prompt IS NULL OR LTRIM(RTRIM(@prompt)) = N''
    BEGIN
        RAISERROR(N'Debe indicar un texto de búsqueda en @prompt.', 16, 1);
        RETURN;
    END;

    IF @top IS NULL OR @top <= 0
    BEGIN
        SET @top = 10;
    END;

    DECLARE @queryEmbedding vector(768);

    SET @queryEmbedding =
        CAST(
            AI_GENERATE_EMBEDDINGS(
                @prompt
                USE MODEL OllamaNomicEmbed
            )
            AS vector(768)
        );

    SELECT
        si.StockItemName AS ProductName,
        ISNULL(si.Brand, N'Not specified') AS Brand,
        ISNULL(c.ColorName, N'Not specified') AS Color,
        ISNULL(si.[Size], N'Not specified') AS ProductSize,
        si.TypicalWeightPerUnit AS TypicalWeight,
        si.RecommendedRetailPrice AS RecommendedPrice,
        ISNULL(si.MarketingComments, N'Not specified') AS MarketingComments
    FROM VECTOR_SEARCH
    (
        TABLE = dbo.ProductSemantic AS ps,
        COLUMN = Embedding,
        SIMILAR_TO = @queryEmbedding,
        METRIC = 'cosine',
        TOP_N = @top
    ) AS vs
    INNER JOIN Warehouse.StockItems AS si
        ON si.StockItemID = ps.StockItemID 
    LEFT JOIN Warehouse.Colors AS c
        ON si.ColorID = c.ColorID
    WHERE CAST(1 - vs.distance AS DECIMAL(19,16)) >= @min_similarity
    ORDER BY vs.distance ASC;
END;
GO

