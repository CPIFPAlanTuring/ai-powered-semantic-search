CREATE TABLE dbo.ProductSemantic
(
    ProductSemanticID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_ProductSemantic
        PRIMARY KEY CLUSTERED,

    StockItemID INT NOT NULL,             -- Unique identifier of the original product

    StockItemName NVARCHAR(100) NOT NULL, -- Product name, useful for displaying results

    SemanticText NVARCHAR(MAX) NOT NULL,  -- Final text used to generate the embedding

    Embedding vector(768) NULL            -- Vector generated by nomic-embed-text
);
GO

